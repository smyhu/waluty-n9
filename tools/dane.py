# Builds currencies.js + flag PNGs for the N9 currency app
import json, os, sys, urllib.request
from babel.numbers import get_currency_name, get_currency_symbol
from babel.core import get_global
import cairosvg

OUT = sys.argv[1]
FLAGS = sys.argv[2]   # flag-icons/flags/4x3
os.makedirs(os.path.join(OUT, 'flags'), exist_ok=True)

rates = json.load(urllib.request.urlopen('http://open.er-api.com/v6/latest/USD'))['rates']

special = {'EUR': 'eu', 'XAF': 'cm', 'XOF': 'sn', 'XCD': 'ag', 'XPF': 'pf', 'ANG': 'cw',
           'XCG': 'cw', 'XDR': 'un', 'CNH': 'cn', 'CLF': 'cl', 'FOK': 'fo', 'GGP': 'gg',
           'IMP': 'im', 'JEP': 'je', 'KID': 'ki', 'TVD': 'tv'}
names_extra = {
    'CNH': ('Chinese Yuan (offshore)', 'juan chiński (offshore)'),
    'FOK': ('Faroese Króna', 'korona farerska'),
    'GGP': ('Guernsey Pound', 'funt Guernsey'),
    'IMP': ('Manx Pound', 'funt manx'),
    'JEP': ('Jersey Pound', 'funt Jersey'),
    'KID': ('Kiribati Dollar', 'dolar Kiribati'),
    'TVD': ('Tuvaluan Dollar', 'dolar Tuvalu'),
    'XCG': ('Caribbean Guilder', 'gulden karaibski'),
    'ZWG': ('Zimbabwe Gold', 'złoto Zimbabwe (ZiG)'),
    'SLE': ('Sierra Leonean Leone', 'leone sierraleońskie'),
    'VES': ('Venezuelan Bolívar', 'boliwar wenezuelski'),
    'MRU': ('Mauritanian Ouguiya', 'ugija mauretańska'),
    'STN': ('São Tomé and Príncipe Dobra', 'dobra Wysp Świętego Tomasza i Książęcej'),
}
# drop currencies that no longer circulate
drop = {'HRK', 'SLL', 'ZWL'}

terr = get_global('territory_currencies')
out = []
missing = []
for code in sorted(rates):
    if code in drop:
        continue
    flag = special.get(code)
    if not flag:
        cand = code[:2].lower()
        if os.path.exists(os.path.join(FLAGS, cand + '.svg')):
            flag = cand
    if not flag:
        missing.append(code)
        flag = ''
    if code in names_extra:
        en, pl = names_extra[code]
    else:
        en = get_currency_name(code, locale='en')
        pl = get_currency_name(code, locale='pl')
    if en == code or pl == code:
        missing.append('name:' + code)
    pl = pl[:1].upper() + pl[1:]
    sym = get_currency_symbol(code, locale='en')
    if sym == code:
        sym = get_currency_symbol(code, locale='pl')
    if code == 'PLN':
        sym = 'zł'
    if sym == code or len(sym) > 4:
        sym = ''
    if flag:
        png = os.path.join(OUT, 'flags', flag + '.png')
        if not os.path.exists(png):
            cairosvg.svg2png(url=os.path.join(FLAGS, flag + '.svg'), write_to=png,
                             output_width=60, output_height=45)
    out.append({'code': code, 'en': en, 'pl': pl, 'sym': sym, 'flag': flag})

with open(os.path.join(OUT, 'currencies.js'), 'w', encoding='utf-8') as f:
    f.write('.pragma library\n// Generated by dane.py: ISO code, English/Polish name (CLDR), symbol, flag file\n')
    f.write('var list = ' + json.dumps(out, ensure_ascii=False, indent=0).replace('\n', '') + ';\n')
print(len(out), 'currencies; missing:', missing)
